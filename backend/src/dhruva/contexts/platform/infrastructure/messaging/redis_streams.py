"""The Redis Streams adapter (ADR-002, ADR-062, ADR-067, ADR-068).

Pure translation between :class:`EventEnvelope` and Redis Streams, and nothing
else. Retry, leasing, ordering, routing and the dead-letter decision all live
elsewhere -- in :mod:`dhruva.contexts.platform.domain.messaging` and in the
relay -- and duplicating any of them here would give the platform two places to
change and one of them would be missed.

This module is the *only* place in the codebase that knows what a stream id is.
Boundary rule R9 (ADR-068) fails the build if a domain or strategy module
imports ``redis``, and the ack token below is deliberately opaque so a consumer
cannot begin to depend on the shape of one.

Why the stream id is generated by Redis, not derived from ``sequence``
----------------------------------------------------------------------
The S05 design proposed ``XADD`` with an explicit id derived from the outbox
``sequence``, so that a relay retry would be idempotent at the transport. It
cannot work, and the reason is worth recording where the code is.

Redis requires an explicitly supplied entry id to be **strictly greater than the
top of the stream**. Streams are per aggregate *type* and carry many aggregates,
while retry is per *message* (ADR-064): sequence 10 may fail, sequences 11 and
12 may succeed, and sequence 10 is then re-offered after them. ``XADD`` with
``10-0`` against a stream topped by ``12-0`` is refused. Falling back to a
generated id on refusal is worse than useless -- a generated id is a millisecond
timestamp, roughly 1.7e12, so a single fallback puts the stream top permanently
beyond every future ``sequence`` and *every* subsequent explicit id fails. The
scheme degrades to generated ids on first use, having added a silent mode.

Nothing is lost by dropping it. Transport-level de-duplication could never have
protected the consumer's side effect anyway, because it happens in a different
transaction from the work. ADR-065 puts the ledger write in the *same*
transaction as the effect it guards, which is strictly stronger. At-least-once
(ADR-062) already states that a duplicate is correct behaviour.

Why a malformed entry raises instead of being skipped
-----------------------------------------------------
ADR-022: ambiguity blocks rather than proceeds. An entry this adapter cannot
read is not skipped -- skipping would process the events around it and leave a
hole nobody sees. It raises, and because the entry was delivered under a
consumer group it stays in the pending list: recoverable with ``XAUTOCLAIM`` or
a re-read from ``0`` once a human has looked at it. Nothing is lost by stopping;
something is lost by continuing.
"""

